import { test } from 'node:test';
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { makePrototypeFixture } from './helpers/prototype-fixture.mjs';
import { runPage } from './helpers/cdp-probe.mjs';

// 用 CDP 轮询探针结果：--dump-dom 会在页面 load 前后取快照，与脚本执行存在竞态，
// 并发跑测试时会偶发「快照截在脚本中间」，无法作为断言依据。
test('资料目录登记原件、本机模拟抽取需授权、候选逐条采纳才入库、撤回清空', async t => {
  const fx = await makePrototypeFixture(t, 'beipal-files-');
  const html = fx.html;
  const probe = `<script>(async()=>{try{
    const check=(v,m)=>{if(!v)throw Error(m)};
    const waitFor=async (fn,msg)=>{const deadline=Date.now()+5000;while(Date.now()<deadline){if(fn())return;await new Promise(r=>setTimeout(r,20))}throw Error(msg)};
    const q=s=>{const el=document.querySelector(s);if(!el)throw Error('缺少元素 '+s);return el};
    const click=s=>q(s).click();
    go('资料目录与云解析');
    check(document.querySelector('main h1').textContent.includes('资料目录'),'入口页未打开');
    check(document.querySelector('main').textContent.includes('还没有登记原件'),'空目录状态缺失');
    const dt=new DataTransfer();
    dt.items.add(new File(['2026-09-01 复查记录：口腔溃疡好转\\n医生建议三个月后复诊'],'demo-note.txt',{type:'text/plain'}));
    const input=q('#file-input');
    input.files=dt.files;input.dispatchEvent(new Event('change',{bubbles:true}));
    check(state.files.length===1,'原件未登记');
    const f=state.files[0];
    check(q('main').textContent.includes('demo-note.txt'),'目录未列出原件');
    await waitFor(()=>f.content.includes('口腔溃疡好转'),'文件读取未完成或内容不正确');
    click('[data-parse="'+f.id+'"]');
    click('[data-parse-run="'+f.id+'"]');
    check(q('#parse-err').textContent.includes('勾选'),'未授权也能抽取');
    check(state.candidates.length===0,'未授权已产生候选');
    q('#parse-consent').checked=true;
    click('[data-parse-run="'+f.id+'"]');
    check(state.candidates.length===2,'候选数量不对：'+state.candidates.length);
    click('[data-drop="'+state.candidates[1].id+'"]');
    check(state.candidates.length===1,'丢弃未生效');
    const before=state.records.length;
    click('[data-accept="'+state.candidates[0].id+'"]');
    check(state.records.length===before+1,'采纳未入库');
    const rec=state.records[0];
    check(rec.kind==='资料库'&&rec.fileId===f.id&&rec.original&&rec.original.title==='demo-note.txt','采纳记录未保留原件引用');
    const box=q('[data-file-private="'+f.id+'"]');
    box.checked=true;box.dispatchEvent(new Event('change',{bubbles:true}));
    check(rec.private===true,'私密原件未同步到记录');
    go('看板');
    click('[data-action=discuss]');
    check(!q('#draft').value.includes('口腔溃疡好转'),'私密原件文本进了 AI 草稿');
    go('资料目录与云解析');
    click('[data-parse="'+f.id+'"]');
    q('#parse-consent').checked=true;
    click('[data-parse-run="'+f.id+'"]');
    check(state.candidates.length>0,'再次抽取无候选');
    click('[data-parse-revoke]');
    check(state.candidates.length===0,'撤回未清空候选');
    window.__filesTest='PASS';
  }catch(e){window.__filesTest='FAIL: '+e.message}})()</script>`;
  const page = html.replace('</body>', probe + '</body>');
  assert.ok(page.includes('__filesTest="PASS"' ) || page.includes("__filesTest='PASS'"), '探针未注入');
  await writeFile(fx.indexPath, page);
  const result = await runPage(fx.url, 'window.__filesTest || ""');
  assert.equal(result, 'PASS');
});
// 回归的是三条容易“看起来对、实际不对”的契约：
// 1) 抽取候选没有日期，采纳时不得拿今天补齐；2) 私密原件的候选必须带标记；
// 3) 撤回只清本机候选/文本缓存，已采纳记录保留，且不能暗示云端删除。
test('候选采纳日期未知、私密原件候选有标记、撤回只清本机缓存且不冒充云删除', async t => {
  const fx = await makePrototypeFixture(t, 'beipal-files-contract-');
  const html = fx.html;
  const probe = `<script>(async()=>{try{
    const check=(v,m)=>{if(!v)throw Error(m)};
    const waitFor=async (fn,msg)=>{const deadline=Date.now()+5000;while(Date.now()<deadline){if(fn())return;await new Promise(r=>setTimeout(r,20))}throw Error(msg)};
    const q=s=>{const el=document.querySelector(s);if(!el)throw Error('缺少元素 '+s);return el};
    const click=s=>q(s).click();
    go('资料目录与云解析');
    const today=new Date().toISOString().slice(0,10);
    const dt=new DataTransfer();
    dt.items.add(new File(['2026-09-01 复查记录：口腔溃疡好转\\n医生建议三个月后复诊'],'private-note.txt',{type:'text/plain'}));
    const input=q('#file-input');
    input.files=dt.files;input.dispatchEvent(new Event('change',{bubbles:true}));
    check(state.files.length===1,'原件未登记');
    const f=state.files[0];
    await waitFor(()=>f.content.includes('口腔溃疡好转'),'文件读取未完成');
    const box=q('[data-file-private="'+f.id+'"]');
    box.checked=true;box.dispatchEvent(new Event('change',{bubbles:true}));
    check(f.private===true,'原件未标为私密');
    click('[data-parse="'+f.id+'"]');
    q('#parse-consent').checked=true;
    click('[data-parse-run="'+f.id+'"]');
    check(state.candidates.length===2,'候选数量不对：'+state.candidates.length);
    check(state.candidates.every(c=>c.private===true),'候选未携带私密状态');
    const row=q('[data-candidate="'+state.candidates[0].id+'"]');
    check(row.textContent.includes('私密原件'),'私密原件候选没有清晰标记');
    check(row.dataset.private==='1','候选行没有私密状态');
    const before=state.records.length;
    click('[data-accept="'+state.candidates[0].id+'"]');
    check(state.records.length===before+1,'采纳未入库');
    const rec=state.records[0];
    check(rec.kind==='资料库'&&rec.private===true,'采纳记录未继承私密状态');
    check(rec.date===''&&rec.datePrecision==='unknown','采纳记录日期应为未知');
    check(rec.date!==today,'采纳记录伪造了今天日期');
    check(dateText(rec)==='日期未知','未知日期显示不对：'+dateText(rec));
    go('病情整理','资料库');
    check(document.querySelector('main').textContent.includes('日期未知'),'资料库未显示日期未知');
    go('资料目录与云解析');
    click('[data-parse="'+f.id+'"]');
    q('#parse-consent').checked=true;
    click('[data-parse-run="'+f.id+'"]');
    check(state.candidates.length>0,'撤回前没有候选');
    const keep=state.records.length,accepted=state.records[0];
    check(f.content.length>0,'撤回前没有文本缓存');
    click('[data-parse-revoke]');
    check(state.candidates.length===0,'撤回未清空候选');
    check(f.content==='','撤回未清空本机文本缓存');
    check(state.records.length===keep,'撤回误删已采纳记录');
    check(accepted.fileId===f.id&&accepted.original&&accepted.original.title==='private-note.txt','撤回未保留已采纳记录的原件引用');
    const toast=q('#toast').textContent;
    check(toast.includes('没有云端副本')&&toast.includes('未上传'),'撤回提示未说明没有云副本：'+toast);
    const note=q('#parse-retention-note').textContent;
    check(note.includes('不会声称已删除云端资料'),'撤回契约未说明不冒充云删除');
    check(document.querySelector('main').textContent.includes('本机文本缓存为空'),'未显示文本缓存为空');
    check(document.querySelector('main').textContent.includes('private-note.txt'),'撤回把登记条目也删了');
    check(!document.querySelector('[data-parse-revoke]'),'撤回后仍显示清空按钮');
    go('授权与隐私');
    check(!document.querySelector('main').textContent.includes('不缓存原件内容'),'隐私页仍宣称不缓存原件内容');
    check(document.querySelector('main').textContent.includes('撤回时清空'),'隐私页未说明撤回时清空');
    go('病情整理','整理草稿 / 核对');
    check(!document.querySelector('main').textContent.includes('不缓存内容'),'整理页仍宣称不缓存内容');
    check(document.querySelector('main').textContent.includes('撤回时清空'),'整理页未说明撤回时清空');
    window.__filesContract='PASS';
  }catch(e){window.__filesContract='FAIL: '+e.message}})()</script>`;
  const page = html.replace('</body>', probe + '</body>');
  assert.ok(page.includes('__filesContract="PASS"') || page.includes("__filesContract='PASS'"), '探针未注入');
  await writeFile(fx.indexPath, page);
  const result = await runPage(fx.url, 'window.__filesContract || ""');
  assert.equal(result, 'PASS');
});
