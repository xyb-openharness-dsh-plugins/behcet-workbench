import { test } from 'node:test';
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { makePrototypeFixture } from './helpers/prototype-fixture.mjs';

test('发作记录可新增未知结束、更正回看并遵守私密出口', async t => {
  const browser = process.env.CHROMIUM || '/usr/bin/chromium';
  const fx = await makePrototypeFixture(t, 'beipal-episode-');
  const html = fx.html;
  const probe = `<script>
  (async () => { try {
    const check=(v,m)=>{if(!v)throw Error(m)};
    go('发作与病程','发作记录');
    document.querySelector('[data-action=add]').click();
    document.querySelector('#entry-date').value='2026-01-02';
    document.querySelector('#entry-site').value='口腔';
    document.querySelector('#entry-text').value='测试私密原文';
    document.querySelector('#entry-source').value='本人转述';
    document.querySelector('#entry-private').checked=true;
    document.querySelector('[data-action=save-episode]').click();
    let r=state.records.at(-1); check(r.endDate==='' && r.site==='口腔','新增字段');
    check(document.querySelector('main').textContent.includes('结束：未知'),'未知结束回看');
    check(!state.selected.has(r.id),'私密默认不选');
    check(episodeFields(r).includes('结束：未知 · 部位：口腔'),'未知结束保留在出口字段');
    document.querySelector('[data-action=discuss]').click();
    check(!document.querySelector('#draft').value.includes('测试私密原文'),'AI 私密过滤');
    go('复诊与准备','就诊准备与导出');
    check(!document.querySelector('#export-preview').textContent.includes('测试私密原文'),'摘要默认过滤');
    let privateChoice=document.querySelector('[data-select="'+r.id+'"]');privateChoice.checked=true;privateChoice.dispatchEvent(new Event('change',{bubbles:true}));
    go('病情一图秀','治疗与事件节点');
    privateChoice=document.querySelector('[data-timeline-select="'+r.id+'"]');privateChoice.checked=true;privateChoice.dispatchEvent(new Event('change',{bubbles:true}));
    go('发作与病程','发作记录');
    document.querySelector('[data-correct="'+r.id+'"]').click();
    document.querySelector('#entry-date').value='';
    document.querySelector('#entry-text').value='';
    document.querySelector('[data-save-correction]').click();
    check(document.querySelector('#entry-date').getAttribute('aria-invalid')==='true' && document.querySelector('#entry-text').getAttribute('aria-describedby')==='episode-errors' && document.activeElement.id==='entry-date' && document.querySelector('#episode-errors').textContent.includes('原文'),'弹窗必填错误可访问');
    document.querySelector('#entry-date').value='2026-01-02';
    document.querySelector('#entry-text').value='测试私密原文';
    document.querySelector('#entry-end').value='2026-01-01';
    document.querySelector('[data-save-correction]').click();
    check(document.querySelector('#dialog').open && r.endDate==='' && document.querySelector('#entry-end').getAttribute('aria-invalid')==='true' && document.activeElement.id==='entry-end' && document.querySelector('#episode-errors').textContent.includes('结束日期不能早于开始日期'), '无效日期不能保存且错误可访问');
    document.querySelector('#entry-end').value='2026-01-05';
    document.querySelector('#entry-site').value='舌';
    document.querySelector('#entry-text').value='更正原文';
    document.querySelector('[data-save-correction]').click();
    check(r.endDate==='2026-01-05' && r.site==='舌' && r.history[0].endDate==='', '更正历史');
    check(!state.selected.has(r.id) && !state.timelineSelected.has(r.id),'私密内容更正后必须重新选择');
    check(document.querySelector('main').textContent.includes('结束：未知') && document.querySelector('main').textContent.includes('测试私密原文'),'旧值回看');
    document.querySelector('[data-correct="'+r.id+'"]').click();
    document.querySelector('#entry-private').checked=false;
    document.querySelector('#entry-text').value='公开新原文';
    document.querySelector('[data-save-correction]').click();
    check(r.history.every(h=>h.private===true),'私密旧版本保留独立标记');
    r.history.push({text:'隐私未知旧版本'},'旧格式未知隐私');
    go('看板');
    check(!document.querySelector('main').innerHTML.includes('隐私未知旧版本') && !document.querySelector('main').innerHTML.includes('旧格式未知隐私'),'未知隐私历史默认不展示');
    check(document.querySelector('main').textContent.includes('公开新原文') && !document.querySelector('main').innerHTML.includes('测试私密原文') && !document.querySelector('main').innerHTML.includes('更正原文'),'首页更多不暴露旧私密版本');
    document.querySelector('[data-action=discuss]').click();
    check(document.querySelector('#draft').value.includes('公开新原文') && document.querySelector('#draft').value.includes('结束：2026-01-05 · 部位：舌') && !document.querySelector('#draft').value.includes('测试私密原文'),'AI 仅含公开当前版本和发作字段');
    go('复诊与准备','就诊准备与导出');
    let choice=document.querySelector('[data-select="'+r.id+'"]');choice.checked=true;choice.dispatchEvent(new Event('change',{bubbles:true}));
    check(document.querySelector('#export-preview').textContent.includes('结束：2026-01-05 · 部位：舌') && !document.querySelector('#export-preview').textContent.includes('测试私密原文'),'摘要仅含所选当前版本和发作字段');
    let captured;const originalCreate=URL.createObjectURL;URL.createObjectURL=blob=>(captured=blob,'blob:test');const oldClick=HTMLAnchorElement.prototype.click;HTMLAnchorElement.prototype.click=function(){};
    document.querySelector('[data-action=download]').click();
    const exported=await captured.text();URL.createObjectURL=originalCreate;HTMLAnchorElement.prototype.click=oldClick;
    check(exported.includes('公开新原文') && exported.includes('结束：2026-01-05 · 部位：舌') && !exported.includes('测试私密原文'),'下载仅含所选当前版本和发作字段');
    go('发作与病程','发作记录');
    check(document.querySelector('main').textContent.includes('测试私密原文'),'本人详情可回看旧私密版本');
    document.querySelector('[data-action=discuss]').click();
    check(document.querySelector('#draft').value.includes('口腔不适'),'公开记录进入草稿');
    state.timelineSelected.add(1);
    document.querySelector('[data-correct="1"]').click();
    document.querySelector('#entry-private').checked=true;
    document.querySelector('[data-save-correction]').click();
    check(!state.selected.has(1) && !state.timelineSelected.has(1) && !document.querySelector('#draft').value, '改为私密后撤销选择并清除旧草稿');
    document.body.dataset.episodeTest='PASS';
  } catch(e) { document.body.dataset.episodeTest='FAIL: '+e.message; } })();
  </script>`;
  await writeFile(fx.indexPath, html.replace('</body>', probe + '</body>'));
  const run = spawnSync(browser, ['--headless', '--no-sandbox', '--disable-gpu', '--dump-dom', fx.url], { encoding:'utf8', timeout:30000 });
  if (run.error?.code === 'ENOENT') { t.skip('Chromium 不可用；设置 CHROMIUM 指向浏览器'); return; }
  assert.equal(run.status, 0, run.stderr);
  assert.match(run.stdout, /data-episode-test="PASS"/, run.stdout.match(/data-episode-test="[^"]*"/)?.[0] || run.stderr);
});
