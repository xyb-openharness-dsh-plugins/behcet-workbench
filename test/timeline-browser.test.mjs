import { test } from 'node:test';
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { makePrototypeFixture } from './helpers/prototype-fixture.mjs';

test('跨科时间线按选择并列同日记录并分别回源', async t => {
  const fx = await makePrototypeFixture(t, 'beipal-timeline-');
  const html = fx.html;
  const probe = `<script>try {
    const check=(v,m)=>{if(!v)throw Error(m)};
    const select=(id,on)=>{let el=document.querySelector('[data-timeline-select="'+id+'"]');el.checked=on;el.dispatchEvent(new Event('change',{bubbles:true}))};
    go('病情一图秀','治疗与事件节点');
    check(document.querySelector('#timeline-results').textContent.includes('尚未选择'),'空状态');
    const live=document.querySelector('[aria-live]');check(live && live.contains(document.querySelector('#timeline-results')),'结果在持久的 aria-live 区域中');
    check(!document.querySelector('[data-timeline-select="3"]').checked,'私密默认排除');
    select(4,true);select(5,true);select(1,true);
    let result=document.querySelector('#timeline-results');
    check(live.isConnected && live.contains(result),'选择变化保留 live 区域');
    check(result.querySelectorAll('section').length===1 && result.querySelectorAll('article').length===3,'同日并列');
    const names=[4,5,1].map(id=>document.querySelector('[data-timeline-source="'+id+'"]').getAttribute('aria-label')||'');
    check(names[0].includes('口腔科') && names[1].includes('眼科') && names[0].includes('口腔科示例记录') && new Set(names).size===3,'来源按钮名称区分科别与记录');
    check(result.textContent.includes('口腔科') && result.textContent.includes('眼科') && !result.textContent.includes('下次复诊想问的问题'),'选择与私密边界');
    document.querySelector('[data-timeline-source="4"]').click();
    check(document.querySelector('#dialog-body').textContent.includes('口腔科合成原件') && !document.querySelector('#dialog-body').textContent.includes('眼科合成原件'),'口腔来源');
    document.querySelector('#dialog').close();
    document.querySelector('[data-timeline-source="5"]').click();
    check(document.querySelector('#dialog-body').textContent.includes('眼科合成原件') && !document.querySelector('#dialog-body').textContent.includes('口腔科合成原件'),'眼科来源');
    document.querySelector('#dialog').close();
    document.querySelector('[data-timeline-source="1"]').click();
    check(!document.querySelector('#dialog-body').textContent.includes('无原件'),'非资料类型不显示缺失原件');
    document.querySelector('#dialog').close();
    select(4,false);check(!document.querySelector('#timeline-results').textContent.includes('口腔科示例记录'),'取消选择');
    select(3,true);check(document.querySelector('#timeline-results').textContent.includes('下次复诊想问的问题'),'显式选择私密');
    go('病情整理','资料库');
    document.querySelector('[data-action=discuss]').click();
    check(document.querySelector('#draft').value.includes('口腔科示例记录'),'更正前草稿');
    document.querySelector('[data-correct="4"]').click();
    document.querySelector('#entry-text').value='口腔科更正内容';
    document.querySelector('[data-save-correction="4"]').click();
    check(!document.querySelector('#draft').value,'非发作更正清除过时 AI 草稿');
    go('病情一图秀','治疗与事件节点');select(4,true);
    let corrected=document.querySelector('[data-timeline-source="4"]').closest('article');
    check(corrected.textContent.includes('口腔科更正内容') && corrected.textContent.includes('已更正'),'时间线标明当前记录已更正');
    corrected.querySelector('button').click();
    check(document.querySelector('#dialog-body').textContent.includes('原始内容') && document.querySelector('#dialog-body').textContent.includes('合成原件：口腔科记录口腔不适'),'来源标明原件为原始内容');
    document.querySelector('#dialog').close();
    document.body.dataset.timelineTest='PASS';
  } catch(e) { document.body.dataset.timelineTest='FAIL: '+e.message; }</script>`;
  await writeFile(fx.indexPath, html.replace('</body>', probe + '</body>'));
  const run = spawnSync(process.env.CHROMIUM || '/usr/bin/chromium', ['--headless','--no-sandbox','--disable-gpu','--dump-dom',fx.url], {encoding:'utf8',timeout:30000});
  if (run.error?.code === 'ENOENT') { t.skip('Chromium 不可用'); return; }
  assert.equal(run.status, 0, run.stderr);
  assert.match(run.stdout, /data-timeline-test="PASS"/, run.stdout.match(/data-timeline-test="[^"]*"/)?.[0] || run.stderr);
});
